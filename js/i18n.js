/**
 * 粗略归类，仅用于图例与配色，不代表严格史学分类。
 * @param {string} name 政权名
 * @param {string} type 数据集提供的 type 字段
 * @param {number} year 该快照年份
 * @param {string} continent 现代层的 CONTINENT 字段
 */
export function classify(name, type, year = 0, continent = '') {
  if (type === 'modern-state') {
    return CONTINENTS[continent] ? `c:${continent}` : 'other';
  }
  const s = `${name || ''} ${type || ''}`;
  for (const [re, cls] of KEYWORD_CLASSES) {
    if (re.test(s)) return cls;
  }
  if (year >= 1800) return 'state';
  return 'other';
}

